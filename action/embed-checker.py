#!/usr/bin/env python3
"""Embed action/check-wporg-compliance.sh into the reusable workflow.

Calling repositories run the reusable workflow with a GITHUB_TOKEN that cannot
read this private repository, so the workflow must not check it out. Instead
the checker script is written out from a heredoc inside the workflow itself.

Run this after every change to action/check-wporg-compliance.sh:

    python action/embed-checker.py

Use --check in CI to fail when the embedded copy is out of date.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "action" / "check-wporg-compliance.sh"
WORKFLOW = ROOT / ".github" / "workflows" / "wporg-compliance.yml"

BEGIN = "# >>> embedded check-wporg-compliance.sh (generated by action/embed-checker.py, do not edit)"
END = "# <<< embedded check-wporg-compliance.sh"
DELIM = "WPPOOL_CHECKER_EOF"


def build_block(indent: str) -> str:
    script = SCRIPT.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
    if DELIM in script:
        sys.exit(f"{SCRIPT} contains the heredoc delimiter {DELIM}")
    if "${{" in script:
        sys.exit(f"{SCRIPT} contains '${{{{', which GitHub would treat as an expression")
    lines = [BEGIN, f'cat > "$RUNNER_TEMP/check-wporg-compliance.sh" <<\'{DELIM}\'']
    lines += script.split("\n")
    lines += [DELIM, END]
    return "\n".join((indent + line) if line else "" for line in lines)


def main() -> None:
    text = WORKFLOW.read_text(encoding="utf-8").replace("\r\n", "\n")
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1:
        sys.exit(f"markers not found in {WORKFLOW}")
    line_start = text.rfind("\n", 0, start) + 1
    indent = text[line_start:start]
    new = text[:line_start] + build_block(indent) + text[end + len(END):]
    if "--check" in sys.argv:
        if new != text:
            sys.exit("Embedded checker is out of date. Run: python action/embed-checker.py")
        print("Embedded checker is up to date.")
        return
    WORKFLOW.write_text(new, encoding="utf-8", newline="\n")
    print(f"Embedded {SCRIPT.name} into {WORKFLOW.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
