#!/usr/bin/env python3
"""Embed the action/ files into the reusable workflow.

Calling repositories run the reusable workflow with a GITHUB_TOKEN that cannot read this
repository's files, so the workflow must not check them out. Instead each file is written
out from a heredoc inside the workflow itself.

Run this after every change to a file listed in EMBEDS:

    python action/embed-checker.py

Use --check in CI to fail when an embedded copy is out of date.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORKFLOW = ROOT / ".github" / "workflows" / "wporg-compliance.yml"

# (source file, heredoc delimiter)
EMBEDS = [
    (ROOT / "action" / "check-wporg-compliance.sh", "WPPOOL_CHECKER_EOF"),
    (ROOT / "action" / "ai-review.py", "WPPOOL_AI_REVIEW_EOF"),
    (ROOT / "action" / "ai-review-rules.md", "WPPOOL_AI_RULES_EOF"),
    # Skill knowledge the AI review appends to its rules.
    (ROOT / "knowledge" / "closure-case-studies.md", "WPPOOL_KNOWLEDGE_EOF"),
    (ROOT / "knowledge" / "compliant-trialware-pattern.md", "WPPOOL_KNOWLEDGE_EOF"),
    (ROOT / "knowledge" / "official-guidelines-and-pcp.md", "WPPOOL_KNOWLEDGE_EOF"),
    (ROOT / "knowledge" / "grep-patterns.md", "WPPOOL_KNOWLEDGE_EOF"),
]


def markers(name):
    return (f"# >>> embedded {name} (generated by action/embed-checker.py, do not edit)",
            f"# <<< embedded {name}")


def build_block(source, delim, indent):
    begin, end = markers(source.name)
    text = source.read_text(encoding="utf-8").replace("\r\n", "\n").rstrip("\n")
    if delim in text:
        sys.exit(f"{source} contains the heredoc delimiter {delim}")
    if "${{" in text:
        sys.exit(f"{source} contains '${{{{', which GitHub would treat as an expression")
    lines = [begin, f'cat > "$RUNNER_TEMP/{source.name}" <<\'{delim}\'']
    lines += text.split("\n")
    lines += [delim, end]
    return "\n".join((indent + line) if line else "" for line in lines)


def embed(text):
    for source, delim in EMBEDS:
        begin, end = markers(source.name)
        start = text.find(begin)
        stop = text.find(end)
        if start == -1 or stop == -1:
            sys.exit(f"markers for {source.name} not found in {WORKFLOW}")
        line_start = text.rfind("\n", 0, start) + 1
        indent = text[line_start:start]
        text = text[:line_start] + build_block(source, delim, indent) + text[stop + len(end):]
    return text


def main():
    text = WORKFLOW.read_text(encoding="utf-8").replace("\r\n", "\n")
    new = embed(text)
    if "--check" in sys.argv:
        if new != text:
            sys.exit("Embedded files are out of date. Run: python action/embed-checker.py")
        print("Embedded files are up to date.")
        return
    WORKFLOW.write_text(new, encoding="utf-8", newline="\n")
    print(f"Embedded {', '.join(s.name for s, _ in EMBEDS)} into {WORKFLOW.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
